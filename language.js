const translatedAttributes = ['aria-label', 'aria-roledescription', 'alt', 'title', 'placeholder'];
const normalizedTranslations = new Map(
  Object.entries(frenchTranslations).map(([source, target]) => [normalizeTranslationKey(source), target])
);
const originalTextNodes = [];
const originalAttributes = [];
const originalTitle = document.title;
const originalDescription = document.querySelector('meta[name="description"]')?.content;
let currentLanguage = 'en';

function translateText(value) {
  if (currentLanguage !== 'fr') return value;
  return frenchTranslations[value] || normalizedTranslations.get(normalizeTranslationKey(value)) || value;
}

function normalizeTranslationKey(value) {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[’‘]/g, "'")
    .replace(/[–—−]/g, '-')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function applyLanguage(language) {
  currentLanguage = language === 'fr' ? 'fr' : 'en';
  document.documentElement.lang = currentLanguage;

  originalTextNodes.forEach(({ node, original }) => {
    const leading = original.match(/^\s*/)?.[0] || '';
    const trailing = original.match(/\s*$/)?.[0] || '';
    const content = original.trim();
    node.textContent = `${leading}${translateText(content)}${trailing}`;
  });

  originalAttributes.forEach(({ element, attribute, original }) => {
    element.setAttribute(attribute, translateText(original));
  });

  document.title = translateText(originalTitle);
  const description = document.querySelector('meta[name="description"]');
  if (description && originalDescription) description.content = translateText(originalDescription);

  const toggle = document.querySelector('[data-language-toggle]');
  if (toggle) {
    toggle.textContent = currentLanguage === 'en' ? 'FR' : 'EN';
    toggle.setAttribute('aria-label', currentLanguage === 'en' ? 'Switch to French' : 'Passer en anglais');
    toggle.setAttribute('aria-pressed', String(currentLanguage === 'fr'));
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.textContent.trim()) originalTextNodes.push({ node, original: node.textContent });
  }

  document.querySelectorAll(translatedAttributes.map((attribute) => `[${attribute}]`).join(',')).forEach((element) => {
    translatedAttributes.forEach((attribute) => {
      if (element.hasAttribute(attribute)) {
        originalAttributes.push({ element, attribute, original: element.getAttribute(attribute) });
      }
    });
  });

  const languageToggle = document.querySelector('[data-language-toggle]');
  languageToggle?.addEventListener('click', () => {
    applyLanguage(currentLanguage === 'en' ? 'fr' : 'en');
    try {
      localStorage.setItem('papyrus-language', currentLanguage);
    } catch (error) {
      console.warn('Could not save the selected language preference.', error);
    }
  });

  let savedLanguage;
  try {
    savedLanguage = localStorage.getItem('papyrus-language');
  } catch (error) {
    console.warn('Could not read the saved language preference.', error);
  }
  applyLanguage(savedLanguage === 'fr' ? 'fr' : 'en');
});

